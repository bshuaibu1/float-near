#!/usr/bin/env node
/**
 * Write the .env a consumer needs to spend from the vault.
 *
 * REUSES THE EXISTING AGENT KEY. It does not generate one, does not call
 * `bind_virtual_agent`, and does not fund anything — those are done, and
 * redoing them would mint a SECOND key, bind it alongside the first, and spend
 * another ~0.12 NEAR funding a gas key nobody asked for. Both would then be
 * able to spend node 0's budget, which is a quiet way to lose track of who can
 * move money.
 *
 * It VERIFIES against the chain before writing, because a .env that names a
 * key which is not bound, or not funded, produces a `vault_pay` that fails at
 * the contract with NotVirtualAgent — and the env file looks perfectly
 * reasonable while it does.
 *
 * The secret is written to a gitignored path and NEVER printed. This repo
 * carries a scar from a CLI that echoed a private key into a terminal and a
 * chat transcript, which is why every script here signs with
 * `sign-with-access-key-file` rather than a plaintext key.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync } from "node:fs";
import { resolve, join } from "node:path";
import { JsonRpcProvider } from "near-api-js";

const ROOT = resolve(import.meta.dirname, "..");
const VAULT = process.env.VAULT ?? "floatv4-testnet.fac.floatv4.testnet";
const TOKEN = process.env.TOKEN ?? "ft.floatv4.testnet";
const RPC = process.env.RPC ?? "https://test.rpc.fastnear.com";
const NETWORK = process.env.NETWORK ?? "testnet";
const KEYS = join(ROOT, ".float", "agent-keys.json");
const OUT = join(ROOT, ".float", "agent.env");

if (!existsSync(KEYS)) {
  console.error(`FATAL: ${KEYS} does not exist — no agent has been created.`);
  console.error(`  Create one:  node packages/create-float/bin/float-agent.mjs \\`);
  console.error(`                 --vault ${VAULT} --owner <owner> --node 0 --network ${NETWORK}`);
  process.exit(1);
}

const raw = JSON.parse(readFileSync(KEYS, "utf8"));
const list = Array.isArray(raw) ? raw : (raw.agents ?? raw.keys ?? []);
const hit = (Array.isArray(list) ? list : []).find(
  (a) => a?.vault === VAULT || a?.vaultId === VAULT || a?.contractId === VAULT,
);
if (!hit) {
  console.error(`FATAL: no agent recorded for ${VAULT} in ${KEYS}.`);
  console.error(`  present: ${JSON.stringify((Array.isArray(list) ? list : []).map((a) => a?.vault ?? "?"))}`);
  process.exit(1);
}
const SECRET = hit.secret ?? hit.privateKey ?? hit.private_key ?? hit.secretKey;
const PUBLIC = hit.publicKey ?? hit.public_key ?? hit.pk;
if (typeof SECRET !== "string" || !SECRET.startsWith("ed25519:")) {
  console.error(`FATAL: no usable secret for ${VAULT}. fields: ${Object.keys(hit).join(", ")}`);
  process.exit(1);
}

// ---- verify against the chain BEFORE writing anything ----------------------
const p = new JsonRpcProvider({ url: RPC });
const near = (y) => (Number(y) / 1e24).toFixed(6);

const keys = (await p.viewAccessKeyList({ accountId: VAULT, blockQuery: { finality: "final" } })).keys;
const entry = keys.find((k) => k.public_key === PUBLIC);
if (!entry) {
  console.error(`FATAL: ${PUBLIC} is not an access key on ${VAULT}.`);
  console.error(`  The gas key was never installed, or was deleted. vault_pay would fail.`);
  process.exit(1);
}
// `GasKeyFunctionCall`, NOT `FunctionCall` — a distinct NEP-611 variant, and
// reading the wrong one reports a restricted key as unrestricted.
const gk = entry.access_key.permission?.GasKeyFunctionCall;
if (!gk) {
  console.error(`FATAL: ${PUBLIC} is on the vault but is not a GAS key.`);
  console.error(`  permission: ${JSON.stringify(entry.access_key.permission).slice(0, 160)}`);
  process.exit(1);
}
const node = await p.callFunction({
  contractId: VAULT,
  method: "get_virtual_agent_node",
  args: { public_key: PUBLIC },
  blockQuery: { finality: "optimistic" },
});
if (node === null || node === undefined) {
  console.error(`FATAL: ${PUBLIC} is installed but NOT bound to a node.`);
  console.error(`  Installing and binding are separate actions and either alone does`);
  console.error(`  nothing. request_payment would fail NotVirtualAgent.`);
  process.exit(1);
}
const balance = BigInt(gk.balance);
// The reservation at the vault's MIN_GAS_FOR_DISPATCH (50 TGas) is ~0.031.
// Below that the key cannot transact at all, however much "burn" it has.
const FLOOR = 31n * 10n ** 21n;

const body = `# Float agent credentials for ${VAULT}
#
# GENERATED by scripts/print-agent-env.mjs. Do not commit: .float/ is
# gitignored and NEAR_VAULT_AGENT_KEY below is a PRIVATE KEY.
#
# The agent is VIRTUAL: there is no separate account. NEAR_VAULT_AGENT_ID is
# the VAULT itself, and the contract works out which node may spend by looking
# at the key that signed (signer_account_pk). That is what makes it cost ~168
# bytes of state instead of the 0.55 NEAR a sub-account stranded forever.
#
# This key can do exactly one thing: call request_payment on this one vault.
# It cannot attach a deposit, cannot reach another contract, and cannot raise
# its own limits. Everything it spends is checked against the per-tx cap, the
# daily cap at every level of the tree, the cooldown and the payee allowlist.

NEAR_VAULT_CONTRACT=${VAULT}
NEAR_VAULT_NETWORK=${NETWORK}
NEAR_VAULT_RPC_URL=${RPC}
NEAR_VAULT_TOKEN=${TOKEN}
NEAR_VAULT_TOKEN_DECIMALS=6

# The agent id IS the vault. Not a typo.
NEAR_VAULT_AGENT_ID=${VAULT}
NEAR_VAULT_AGENT_KEY=${SECRET}
`;

mkdirSync(join(ROOT, ".float"), { recursive: true });
if (existsSync(OUT)) rmSync(OUT);
writeFileSync(OUT, body, "utf8");
if (!existsSync(OUT)) {
  console.error(`FATAL: ${OUT} was not written.`);
  process.exit(1);
}

console.log(`\n  VERIFIED ON CHAIN — all of this was already done:`);
console.log(`    key          ${PUBLIC}`);
console.log(`    bound to     node ${node}`);
console.log(`    may call     ${JSON.stringify(gk.method_names)} on ${gk.receiver_id}`);
console.log(`    gas balance  ${near(balance)} NEAR${balance < FLOOR ? "   <-- BELOW the ~0.031 reservation floor, top it up" : ""}`);
console.log(`\n  written to   ${OUT}   (gitignored)`);
console.log(`\n  Contents, with the private key redacted:\n`);
for (const line of body.split("\n")) {
  if (line.startsWith("NEAR_VAULT_AGENT_KEY=")) {
    console.log(`    NEAR_VAULT_AGENT_KEY=ed25519:<redacted — it is in the file>`);
  } else if (line.trim()) {
    console.log(`    ${line}`);
  }
}
console.log();
